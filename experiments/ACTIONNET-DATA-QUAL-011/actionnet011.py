#!/usr/bin/env python3
"""Generate fresh, failure-focused unresolved-appeal repair data."""

from __future__ import annotations

import hashlib
import importlib.util
import json
from collections import Counter
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent
BASE_PATH = ROOT.parent / "ACTIONNET-DATA-QUAL-009" / "actionnet_multigen.py"
PROTOCOL_ID = "ACTIONNET-DATA-QUAL-011"
RESULT_ID = "ACTIONNET-DATA-QUAL-011-result-v1.0.0"
DATASET_ID = "ACTIONNET-UNRESOLVED-APPEAL-FOCUSED-v11.0.0"
TRAIN_SEED = 26090510
VALIDATION_SEED = 26090520
TRAIN_FAMILIES = tuple(range(500, 508))
VALIDATION_FAMILIES = tuple(range(540, 544))
RESERVED_CONFIRMATION_FAMILIES = tuple(range(560, 568))
RESERVED_TRANSFER_FAMILIES = tuple(range(580, 588))
TRAIN_RENDERERS = (
    "APPEAL_CLOCK_LEDGER",
    "APPEAL_DEADLINE_CARD",
    "APPEAL_EVENT_MATRIX",
    "APPEAL_DISPOSITION_TIMELINE",
)
VALIDATION_RENDERER = "HELDOUT_APPEAL_REVIEW_REGISTER"
PREDECESSOR_FAMILIES = set(range(300, 324)) | set(range(340, 346)) | set(range(400, 407)) | set(range(420, 427)) | set(range(440, 444))
PREDECESSOR_RENDERERS = {
    "CHRONOLOGY_LEDGER", "AUTHORIZATION_WORKPAD", "QUEUE_MATRIX", "STATE_TRANSITION_CARD",
    "DEPENDENCY_GRAPH_PACKET", "DECISION_CLOCK_GRID", "MULTI_SYSTEM_JOURNAL", "STATE_DELTA_PACKET",
    "QUEUE_CONTROL_SHEET", "CROSS_FORMAT_REGISTER",
}


def _load_base():
    spec = importlib.util.spec_from_file_location("actionnet009_base_for_v11", BASE_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load predecessor generator: {BASE_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.PROTOCOL_ID = PROTOCOL_ID
    # This successor is deliberately mechanism-focused. Every pivotal slot is
    # an unresolved-appeal intervention; invariance/contextual slots are
    # generated by the inherited engine but excluded from the released corpus.
    module.FOCUSED_PIVOTAL_SCHEDULE = ("UNRESOLVED_APPEAL",)
    return module


BASE = _load_base()


def canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def digest(value: Any) -> str:
    payload = value if isinstance(value, bytes) else canonical(value).encode("utf-8")
    return "sha256:" + hashlib.sha256(payload).hexdigest()


def render(style: str, trajectory: dict[str, Any]) -> tuple[str, str]:
    state = BASE.public_state(trajectory["initial_state"])
    events = trajectory["submitted_events"]
    domain = trajectory["domain"]
    clock = state["request"]["query_time"]
    lines = "\n".join(f"APPEAL_EVENT::{BASE.event_text(event)}" for event in events)
    if style == "APPEAL_CLOCK_LEDGER":
        return "text/plain;profile=appeal-clock-ledger-v1", (
            f"APPEAL_CLOCK_LEDGER domain={domain}\nDECISION_CLOCK={clock}\nINITIAL_TYPED_STATE={canonical(state)}\n"
            f"UNSORTED_APPEAL_EVENTS_BEGIN\n{lines}\nUNSORTED_APPEAL_EVENTS_END\n"
            "Resolve an appeal only when OPEN_APPEAL and RESOLVE_APPEAL execute at or before the decision clock. "
            "A later resolution remains deferred and cannot close the appeal."
        )
    if style == "APPEAL_DEADLINE_CARD":
        compact = " || ".join(BASE.event_text(event) for event in events)
        return "text/plain;profile=appeal-deadline-card-v1", (
            f"APPEAL_DEADLINE_CARD<{domain}> CLOCK::{clock} STATE::{canonical(state)} SUBMISSIONS::{compact} "
            "ORDER::time,priority,sequence,event_id RULE::future_resolution_is_deferred"
        )
    if style == "APPEAL_EVENT_MATRIX":
        return "application/json;profile=appeal-event-matrix-v1", canonical({
            "domain": domain,
            "decision_clock": clock,
            "typed_initial_state": state,
            "submitted_events_unordered": events,
            "canonical_order": ["time", "priority", "sequence", "event_id"],
            "appeal_rule": "RESOLVE_APPEAL closes an open appeal only when executed by the decision clock",
            "late_event_rule": "DEFER",
        })
    if style == "APPEAL_DISPOSITION_TIMELINE":
        return "text/plain;profile=appeal-disposition-timeline-v1", (
            f"APPEAL_DISPOSITION_TIMELINE domain={domain}; cutoff={clock}; typed_start={canonical(state)}. "
            "The following submissions are unordered. Execute through the cutoff and defer future entries. "
            f"{lines}"
        )
    if style == VALIDATION_RENDERER:
        return "text/plain;profile=heldout-appeal-review-register-v1", (
            f"Held-out appeal review register for {domain}. Controlling time={clock}. Start record={canonical(state)}. "
            "Sort the submitted entries by time, priority, sequence, and identifier. Only entries at or before the "
            f"controlling time execute; later entries remain queued. {lines}"
        )
    raise ValueError(style)


def renderer_registry() -> tuple[dict[str, str], list[dict[str, Any]]]:
    styles = (*TRAIN_RENDERERS, VALIDATION_RENDERER)
    mapping = {style: BASE.opaque("renderer", PROTOCOL_ID, style, "v1") for style in styles}
    records = [{
        "lineage_id": lineage,
        "lineage_type": "renderer",
        "version": "1.0.0",
        "content_sha256": digest({"style": style, "schema": "appeal-boundary-render-v11"}),
        "parents": [],
        "authority": "EDON Research Lab",
        "transformation": "render-focused-appeal-boundary-v1",
    } for style, lineage in mapping.items()]
    return mapping, records


def focused_split(
    split: str,
    seed: int,
    families: tuple[int, ...],
    pairs_per_institution: int,
    domains: tuple[str, ...],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    trajectories, pairs, lineages, audit = BASE.generate_split(
        split, seed, families, pairs_per_institution, domains, "UNRESOLVED_APPEAL_FOCUS"
    )
    selected_pairs = [
        pair for pair in pairs
        if pair["pair_class"] == "PIVOTAL" and pair["intervention_family"] == "UNRESOLVED_APPEAL"
    ]
    pair_ids = {pair["counterfactual_pair_id"] for pair in selected_pairs}
    selected_trajectories = [
        trajectory for trajectory in trajectories
        if trajectory["counterfactual_pair_id"] in pair_ids
    ]
    return selected_trajectories, selected_pairs, lineages, audit


def record(trajectory: dict[str, Any], style: str, renderer_ids: dict[str, str]) -> dict[str, Any]:
    media_type, content = render(style, trajectory)
    decision = trajectory["outcome"]["decision"]
    return {
        "case_id": BASE.opaque("case", PROTOCOL_ID, trajectory["trajectory_id"], style, "CERTIFICATE"),
        "input": {
            "observation": {
                "renderer_lineage": renderer_ids[style],
                "media_type": media_type,
                "content": content,
            },
            "query": (
                "Execute the queue through the decision clock and return one canonical non-authoritative certificate. "
                "An appeal is unresolved when its resolution event is deferred; in that state the disposition is "
                "CONTESTED and must never be ALLOW."
            ),
        },
        "target": dict(trajectory["outcome"]),
        "metadata": {
            "trajectory_id": trajectory["trajectory_id"],
            "counterfactual_pair_id": trajectory["counterfactual_pair_id"],
            "pair_class": trajectory["pair_class"],
            "variant": trajectory["variant"],
            "intervention_family": trajectory["intervention_family"],
            "pair_mechanism": trajectory["pair_mechanism"],
            "generator_lineage": trajectory["generator_lineage"],
            "generator_profile": trajectory["generator_profile"],
            "source_lineage": trajectory["source_lineage"],
            "institution_lineage": trajectory["institution_lineage"],
            "authority_graph_lineage": trajectory["authority_graph_lineage"],
            "workflow_graph_lineage": trajectory["workflow_graph_lineage"],
            "semantic_family": trajectory["semantic_family"],
            "selected_renderer": style,
            "task_type": "CERTIFICATE",
            "decision": decision,
            "sample_weight": 8.0 if decision != "ALLOW" else 6.0,
            "safety_critical": decision != "ALLOW",
            "training_fields": ["input", "target"],
        },
    }


def _event(trajectory: dict[str, Any], operation: str) -> dict[str, Any]:
    matches = [event for event in trajectory["submitted_events"] if event["operation"] == operation]
    if len(matches) != 1:
        raise ValueError(f"expected one {operation} event")
    return matches[0]


def appeal_boundary_exact(pair: dict[str, Any]) -> bool:
    base = pair["base"]
    comparison = pair["comparison"]
    base_resolve = _event(base, "RESOLVE_APPEAL")
    comparison_resolve = _event(comparison, "RESOLVE_APPEAL")
    base_clock = base["initial_state"]["request"]["query_time"]
    comparison_clock = comparison["initial_state"]["request"]["query_time"]
    return (
        base_resolve["time"] <= base_clock
        and comparison_resolve["time"] > comparison_clock
        and base_resolve["event_id"] in base["execution_receipt"]["executed_event_ids"]
        and comparison_resolve["event_id"] in comparison["execution_receipt"]["deferred_event_ids"]
        and base["outcome"]["decision"] == "ALLOW"
        and comparison["outcome"]["decision"] == "CONTESTED"
    )


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "records": len(rows),
        "case_ids": len({row["case_id"] for row in rows}),
        "pair_ids": len({row["metadata"]["counterfactual_pair_id"] for row in rows}),
        "decision_counts": dict(sorted(Counter(row["target"]["decision"] for row in rows).items())),
        "renderer_counts": dict(sorted(Counter(row["metadata"]["selected_renderer"] for row in rows).items())),
        "task_counts": dict(sorted(Counter(row["metadata"]["task_type"] for row in rows).items())),
        "weight_sum": sum(float(row["metadata"]["sample_weight"]) for row in rows),
    }


def generate() -> dict[str, Any]:
    renderer_ids, renderer_lineages = renderer_registry()
    train_trajectories, train_pairs, train_lineages, train_audit = focused_split(
        "train", TRAIN_SEED, TRAIN_FAMILIES, 18,
        ("appeal-review-board", "benefits-appeal", "licensing-appeal", "records-appeal"),
    )
    validation_trajectories, validation_pairs, validation_lineages, validation_audit = focused_split(
        "focused_validation", VALIDATION_SEED, VALIDATION_FAMILIES, 12,
        ("water-rights-appeal", "credential-appeal", "aviation-appeal", "research-access-appeal"),
    )
    train_rows = [
        record(trajectory, style, renderer_ids)
        for trajectory in sorted(train_trajectories, key=lambda item: item["trajectory_id"])
        for style in TRAIN_RENDERERS
    ]
    validation_rows = [
        record(trajectory, VALIDATION_RENDERER, renderer_ids)
        for trajectory in sorted(validation_trajectories, key=lambda item: item["trajectory_id"])
    ]
    lineage_map = {
        item["lineage_id"]: item
        for item in [*renderer_lineages, *train_lineages, *validation_lineages]
    }
    train_summary = summarize(train_rows)
    validation_summary = summarize(validation_rows)
    train_cases = {row["case_id"] for row in train_rows}
    validation_cases = {row["case_id"] for row in validation_rows}
    train_pairs_ids = {row["metadata"]["counterfactual_pair_id"] for row in train_rows}
    validation_pairs_ids = {row["metadata"]["counterfactual_pair_id"] for row in validation_rows}
    train_families = {row["metadata"]["semantic_family"] for row in train_rows}
    validation_families = {row["metadata"]["semantic_family"] for row in validation_rows}
    all_rows = train_rows + validation_rows
    all_trajectories = train_trajectories + validation_trajectories
    controls = {
        "registered_counts": len(train_rows) == 768 and len(validation_rows) == 64,
        "registered_pair_counts": len(train_pairs) == 96 and len(validation_pairs) == 32,
        "certificate_only": all(row["metadata"]["task_type"] == "CERTIFICATE" for row in all_rows),
        "unresolved_appeal_only": all(row["metadata"]["pair_mechanism"] == "UNRESOLVED_APPEAL" for row in all_rows),
        "pivotal_only": all(row["metadata"]["pair_class"] == "PIVOTAL" for row in all_rows),
        "train_decisions_balanced": train_summary["decision_counts"] == {"ALLOW": 384, "CONTESTED": 384},
        "validation_decisions_balanced": validation_summary["decision_counts"] == {"ALLOW": 32, "CONTESTED": 32},
        "appeal_boundary_exact": all(appeal_boundary_exact(pair) for pair in train_pairs + validation_pairs),
        "independent_reference_engines_exact": train_audit["engine_disagreements"] == validation_audit["engine_disagreements"] == 0,
        "independent_schedulers_exact": train_audit["scheduler_disagreements"] == validation_audit["scheduler_disagreements"] == 0,
        "transition_engines_exact": train_audit["transition_disagreements"] == validation_audit["transition_disagreements"] == 0,
        "decision_clock_exact": train_audit["decision_clock_violations"] == validation_audit["decision_clock_violations"] == 0,
        "event_operands_visible": all(
            BASE.event_operands_visible(row["input"]["observation"]["content"], trajectory["submitted_events"])
            for trajectory in all_trajectories
            for row in all_rows
            if row["metadata"]["trajectory_id"] == trajectory["trajectory_id"]
        ),
        "binding_authority_false": all(row["target"].get("binding_authority") is False for row in all_rows),
        "model_inputs_only_observation_query": all(set(row["input"]) == {"observation", "query"} for row in all_rows),
        "unique_case_ids": len(train_cases) == len(train_rows) and len(validation_cases) == len(validation_rows),
        "train_validation_cases_disjoint": not train_cases & validation_cases,
        "train_validation_pairs_disjoint": not train_pairs_ids & validation_pairs_ids,
        "train_validation_families_disjoint": not train_families & validation_families,
        "train_validation_renderers_disjoint": {row["metadata"]["selected_renderer"] for row in train_rows}.isdisjoint(
            {row["metadata"]["selected_renderer"] for row in validation_rows}
        ),
        "predecessor_families_disjoint": not (train_families | validation_families) & PREDECESSOR_FAMILIES,
        "predecessor_renderers_disjoint": not (set(TRAIN_RENDERERS) | {VALIDATION_RENDERER}) & PREDECESSOR_RENDERERS,
        "new_protocol_namespace": PROTOCOL_ID not in {"ACTIONNET-DATA-QUAL-009", "ACTIONNET-DATA-QUAL-010"},
        "heldout_renderer_validation_only": validation_summary["renderer_counts"] == {VALIDATION_RENDERER: 64},
        "no_raw_sensitive_fields": all(
            not any(term in row["input"]["observation"]["content"].lower() for term in ("email", "phone", "address", "ssn"))
            for row in all_rows
        ),
        "no_duplicate_lineage_ids": len(lineage_map) == len({item["lineage_id"] for item in lineage_map.values()}),
    }
    return {
        "schema_version": "actionnet-data-qual-011-generated.v1",
        "protocol_id": PROTOCOL_ID,
        "result_id": RESULT_ID,
        "dataset_id": DATASET_ID,
        "datasets": {"train": train_rows, "focused_validation": validation_rows},
        "canonical_trajectories": all_trajectories,
        "lineages": list(lineage_map.values()),
        "controls": controls,
        "audits": {
            "train": train_summary,
            "focused_validation": validation_summary,
            "train_generator": train_audit,
            "validation_generator": validation_audit,
            "aggregate_target_sha256": digest([row["target"] for row in all_rows]),
        },
        "protected": {
            "confirmation_families": list(RESERVED_CONFIRMATION_FAMILIES),
            "transfer_families": list(RESERVED_TRANSFER_FAMILIES),
            "public_materialized": False,
            "protected_materialized": False,
            "real_institution_materialized": False,
        },
    }